// Local-artifact UI acceptance. This never operates a signed-in publishing page.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.argv[2]);
const input=path.resolve(process.argv[3]),out=path.resolve(process.argv[4]);
const logic=require('../templates/publication-desk/manual-desk.js');
(async()=>{
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({headless:true,channel:'msedge'});
  const report={tests:[],network:[],errors:[],evidence_kind:'local_artifact',uploads:false,published:false};
  const ok=name=>report.tests.push(name);
  try{
    const context=await browser.newContext({acceptDownloads:true,viewport:{width:1280,height:920}});
    await context.route(/^https?:/,r=>{report.network.push(r.request().url());return r.abort();});
    const page=await context.newPage();page.on('pageerror',e=>report.errors.push(e.message));
    await page.goto(pathToFileURL(input).href);
    const cards=page.locator('details.platform-card'),xhs=page.locator('[data-platform=xiaohongshu]');
    assert.equal(await cards.count(),5);
    assert.equal(await page.locator('.cover-shelf,.cover-pk,.cover-matrix,.upload-paths').count(),0);
    assert.equal(await page.getByRole('heading',{name:'内容依据与禁止扩写（不属于发布文案）',exact:true}).count(),0);
    assert.equal(await page.locator('details.platform-card[open]').count(),1);
    assert.equal(await xhs.getAttribute('open'),'');
    ok('Platform panels replace central assets and non-public editorial displays');
    const original=await page.locator('#desk-data').textContent(),data=JSON.parse(original);
    for(const [key,p] of Object.entries(data.items[0].platforms)){
      const panel=page.locator('[data-platform='+key+']');
      assert.equal(await panel.locator('video').count(),1);
      const shown=await panel.locator('img[data-cover-id]').evaluateAll(nodes=>nodes.map(n=>n.dataset.coverId));
      assert.ok(shown.every(id=>logic.platformCoverIds(data.items[0],key).includes(id)));
      assert.equal(await panel.getByLabel(/成片文件/).count(),1);
    }
    ok('Each platform owns its video path, preview, assigned covers and copy');
    await page.getByRole('button',{name:'全部展开',exact:true}).click();
    assert.equal(await page.locator('details.platform-card[open]').count(),5);
    await page.getByRole('button',{name:'全部收起',exact:true}).click();
    assert.equal(await page.locator('details.platform-card[open]').count(),0);
    await xhs.locator('summary.platform-head').click();
    assert.equal(await page.locator('details.platform-card[open]').count(),1);
    await page.screenshot({path:path.join(out,'actual-page-desktop.png'),fullPage:true});
    await page.setViewportSize({width:412,height:915});
    await page.screenshot({path:path.join(out,'actual-page-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1280,height:920});
    ok('Expand all, collapse all and individual platform disclosure work');
    assert.equal(await xhs.locator('.cover-test-variant').count(),3);
    assert.equal(await xhs.locator('.main-cover-panel').count(),1);
    const beforeCopy=JSON.stringify(data.items[0].platforms.xiaohongshu.fields);
    const primary=path.resolve(process.argv[5]||path.join(path.dirname(input),'primary-fixture.png')).replaceAll('\\','/');
    await xhs.getByLabel('小红书 主封面图片路径',{exact:true}).fill(primary);
    await page.getByRole('button',{name:'刷新素材预览',exact:true}).click();
    assert.equal(await page.locator('details.platform-card[open]').count(),1);
    assert.equal(await xhs.locator('.cover-test-variant').count(),3);
    ok('Independent primary path does not consume or replace A/B/F PK slots');
    const names=data.items[0].cover_pk.candidates.map(c=>c.name);
    await xhs.getByRole('checkbox',{name:'小红书 测试 '+names[1],exact:true}).uncheck();
    await xhs.getByRole('checkbox',{name:'小红书 测试 '+names[2],exact:true}).uncheck();
    assert.equal(await xhs.locator('.cover-test-variant').count(),1);
    assert.equal(await page.locator('[data-platform=douyin] .cover-test-variant').count(),3);
    await xhs.getByRole('checkbox',{name:'小红书 测试 '+names[1],exact:true}).check();
    await xhs.getByRole('checkbox',{name:'小红书 测试 '+names[2],exact:true}).check();
    assert.equal(await xhs.locator('.cover-test-variant').count(),3);
    ok('One to three XHS PK candidates preserve primary and other platform selections');
    const download=page.waitForEvent('download');
    await page.getByRole('button',{name:'导出发布数据 JSON',exact:true}).click();
    const exported=path.join(out,'ui-edited.json');await(await download).saveAs(exported);
    const changed=JSON.parse(fs.readFileSync(exported,'utf8'));logic.validate(changed);
    const plan=logic.coverTestPlan(changed.items[0],'xiaohongshu',JSON.parse(await page.locator('#platform-policy').textContent()));
    assert.equal(plan.total_cover_count,4);assert.equal(plan.max_candidates,3);
    assert.equal(plan.candidate_ids.length,3);assert.ok(plan.main_cover_id);
    assert.equal(JSON.stringify(changed.items[0].platforms.xiaohongshu.fields),beforeCopy);
    assert.deepEqual(changed.editorial_context,data.editorial_context);
    assert.equal(changed.ui_state.platform_panels['main::xiaohongshu'],true);
    assert.equal(changed.ui_state.platform_panels['main::douyin'],false);
    ok('Export preserves distinct cover roles, panel states and unchanged public copy');
    const saved=page.waitForEvent('download');await page.getByRole('button',{name:'保存当前页面',exact:true}).click();
    const savedPath=path.join(out,'saved-desk.html');await(await saved).saveAs(savedPath);
    await page.goto(pathToFileURL(savedPath).href);
    assert.equal(await page.locator('details.platform-card[open]').count(),1);
    assert.equal(await page.locator('[data-platform=xiaohongshu]').getAttribute('open'),'');
    assert.equal((await page.getByLabel('小红书 主封面图片路径',{exact:true}).inputValue()).replaceAll('\\','/'), '"'+primary+'"');
    ok('Saved standalone HTML reopens with selected primary and disclosure state');
    await page.screenshot({path:path.join(out,'desktop-xiaohongshu.png'),fullPage:true});
    await page.setViewportSize({width:412,height:915});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await page.screenshot({path:path.join(out,'mobile-xiaohongshu.png'),fullPage:true});
    ok('412px layout has no horizontal page overflow');
    assert.equal(report.network.length,0);assert.equal(report.errors.length,0);report.status='passed';
  }catch(e){report.status='failed';report.error=e.stack;process.exitCode=1;}
  finally{await browser.close();fs.writeFileSync(path.join(out,'browser-report.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));}
})();
