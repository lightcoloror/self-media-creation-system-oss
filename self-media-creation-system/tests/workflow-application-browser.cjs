/* UI regression against generated local artifacts. Never submits a review or publishes. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.argv[2]);
const input=process.argv[3],out=process.argv[4],reviewURL=process.argv[5];
(async()=>{
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({headless:true});
  const results={},errors=[];
  try{
    const context=await browser.newContext({acceptDownloads:true,viewport:{width:1440,height:1000}});
    const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
    await context.route(/^https?:/,route=>route.request().url().startsWith(reviewURL)?route.continue():route.abort());
    await page.addInitScript(()=>{Object.defineProperty(navigator,'clipboard',{value:{writeText:async value=>{window.__lastCopied=value;}}});});
    await page.goto(pathToFileURL(input).href);
    assert.doesNotMatch(await page.locator('.message').innerText(),/有未保存修改/);
    assert.equal(await page.locator('.platform-card').count(),5);
    const cards=page.locator('.platform-card');
    for(const key of ['快手','微信视频号']){
      const card=cards.filter({has:page.locator('.platform-head',{hasText:key})});
      assert.equal(await card.getByLabel('标题 / 首句',{exact:true}).count(),0);
      assert.equal(await card.getByLabel('短标题',{exact:true}).count(),key==='微信视频号'?1:0);
    }
    await page.locator('img').evaluateAll(images=>images.forEach(i=>i.loading='eager'));
    await page.waitForFunction(()=>[...document.images].every(i=>i.complete&&i.naturalWidth>0));
    results.images=await page.locator('img').count();
    assert.equal(await page.locator('.cover-shelf img').count(),4);
    assert.match(await page.locator('#local-preparation').innerText(),/多方案对比待补齐/);
    results.honest_comparison_gap=true;
    const xhs=cards.filter({has:page.locator('.platform-head',{hasText:'小红书'})});
    const title=xhs.getByLabel('标题 / 首句',{exact:true});
    const before=await title.inputValue();
    await title.fill('测试出现我爱你');
    assert.match(await page.locator('#local-preparation').innerText(),/禁止提前透露/);
    await title.fill(before);
    const disclosure=xhs.getByLabel('小红书 disclosure 核验状态');
    const tagsCheck=xhs.getByLabel('小红书 tags 核验状态');
    await xhs.locator('.platform-requirements > summary').click();
    await disclosure.selectOption('confirmed');
    await tagsCheck.selectOption('confirmed');
    await xhs.getByLabel('简介 / 正文',{exact:true}).fill('测试修改后的正文');
    assert.equal(await disclosure.inputValue(),'pending');
    assert.equal(await tagsCheck.inputValue(),'confirmed');
    await tagsCheck.selectOption('pending');
    results.only_affected_checks_invalidated=true;
    assert.match(await xhs.getByLabel('小红书 整段发布文案').inputValue(),/测试修改后的正文/);
    await xhs.getByRole('button',{name:'复制整段',exact:true}).click();
    assert.match(await page.evaluate(()=>window.__lastCopied),/测试修改后的正文/);
    const sourceData=JSON.parse(await page.locator('#desk-data').textContent());
    const firstCover=sourceData.items[0].covers[0];
    const swap=sourceData.items[0].covers.find(c=>c.id==='cover-4x3');
    const firstImage=page.locator('.cover-shelf img').first();
    const firstPath=page.locator('.cover-shelf textarea').first();
    await firstPath.fill(swap.path);
    await page.waitForFunction(()=>document.querySelector('.cover-shelf img').naturalWidth===1448);
    assert.match(await firstImage.getAttribute('src'),/^file:/);
    assert.match(await page.locator('#local-preparation').innerText(),/比例不适用/);
    await firstPath.fill(firstCover.path);
    await page.waitForFunction(()=>document.querySelector('.cover-shelf img').naturalWidth===1086);
    results.preview_and_copy_follow_edits=true;
    const jsonDownload=page.waitForEvent('download');
    await page.getByRole('button',{name:'导出发布数据 JSON',exact:true}).click();
    const jsonPath=path.join(out,'浏览器编辑副本.json');await(await jsonDownload).saveAs(jsonPath);
    const saved=JSON.parse(fs.readFileSync(jsonPath,'utf8'));
    assert.equal(saved.items[0].platforms.xiaohongshu.fields.body,'测试修改后的正文');
    assert.equal(Object.keys(saved.items[0].platforms).length,5);
    assert.equal(saved.items[0].platforms.xiaohongshu.record.status,'prepared');
    const htmlDownload=page.waitForEvent('download');
    await page.getByRole('button',{name:'保存当前页面',exact:true}).click();
    const savedPath=path.join(out,'浏览器保存副本.html');await(await htmlDownload).saveAs(savedPath);
    await page.goto(pathToFileURL(savedPath).href);
    assert.equal(await page.locator('.platform-card').filter({has:page.locator('.platform-head',{hasText:'小红书'})}).getByLabel('简介 / 正文',{exact:true}).inputValue(),'测试修改后的正文');
    assert.equal(await page.locator('#delivery-status').getAttribute('data-state'),'draft');
    results.save_reopen_preserves_edits=true;
    await page.goto(pathToFileURL(input).href);
    await page.screenshot({path:path.join(out,'发布页桌面.png')});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(out,'发布页手机.png')});
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
    assert.ok(overflow<=1,'mobile page horizontal overflow: '+overflow);
    results.mobile_horizontal_overflow=overflow;
    if(reviewURL){
      await page.setViewportSize({width:1440,height:1000});
      await page.goto(reviewURL);
      await page.locator('.queue-item').nth(1).click();
      await page.waitForFunction(()=>document.getElementById('player').readyState>=2);
      await page.evaluate(()=>{const v=document.getElementById('player');v.pause();v.currentTime=1.65;});
      await page.waitForFunction(()=>Math.abs(document.getElementById('player').currentTime-1.65)<.02&&document.querySelector('.cue-animated'));
      const initial=await page.locator('.review-cue[data-layer="dialogue"] .cue-animated').first().getAttribute('style');
      await page.waitForTimeout(120);
      assert.equal(await page.locator('.review-cue[data-layer="dialogue"] .cue-animated').first().getAttribute('style'),initial,'paused motion must not drift');
      await page.evaluate(()=>{document.getElementById('player').currentTime=1.95;});
      await page.waitForFunction(previous=>document.querySelector('.review-cue[data-layer="dialogue"] .cue-animated')?.getAttribute('style')!==previous,initial);
      const final=await page.locator('.review-cue[data-layer="dialogue"] .cue-animated').first().getAttribute('style');
      assert.notEqual(initial,final);
      const font=await page.evaluate(async()=>{try{return (await document.fonts.load('16px ReviewYouYuan')).length>0;}catch{return false;}});
      assert.equal(font,true,'requested local font must really load');
      assert.match(await page.locator('.review-cue[data-layer="dialogue"]').first().evaluate(e=>getComputedStyle(e).fontFamily),/ReviewYouYuan/);
      const originalClassColor=await page.evaluate(()=>{
        const e=document.querySelector('.review-cue[data-speaker="child"]');
        e.dataset.emphasis='false';e.dataset.motion='soft_pop';const a=getComputedStyle(e).color;
        e.dataset.motion='bounce';return {a,b:getComputedStyle(e).color};
      });
      assert.equal(originalClassColor.a,originalClassColor.b);
      await page.screenshot({path:path.join(out,'原片动效审核.png')});
      results.original_range_seek=true;results.real_font_loaded=font;results.motion_changes_with_media_clock=true;
      results.paused_motion_stable=true;
      results.same_speaker_base_color_stable=true;
    }
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(out,'浏览器验收.json'),JSON.stringify({status:'passed',...results,errors,published:false,human_review_submitted:false},null,2));
    console.log(JSON.stringify({status:'passed',...results}));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
